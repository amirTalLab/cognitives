// Regenerates lib/experiment-runtime/stimuli/drm-lists.ts from the hand-built experiment.
//
//   node scripts/build-drm-stimuli.mjs
//
// The port has to present the SAME words as app/drm, or it is a different experiment with
// the same name. Copying them by hand across five themed lists, fifty study words and
// twenty-five foils is exactly the kind of transcription that goes wrong once and is then
// invisible — a dropped word shortens a list, a mistyped one becomes an intrusion nobody
// can explain. So they are read from the original module and written out mechanically.
//
// Run it again whenever lib/drm/word-lists.ts changes.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE = join(process.cwd(), 'lib', 'drm', 'word-lists.ts');
const TARGET = join(process.cwd(), 'lib', 'experiment-runtime', 'stimuli', 'drm-lists.ts');

if (!existsSync(SOURCE)) {
  console.error(`Cannot find ${SOURCE}. Run this from the repository root.`);
  process.exit(1);
}

const src = readFileSync(SOURCE, 'utf8');

/** Pulls one `export const NAME ... = [ ... ];` block out of the source, braces balanced. */
function block(name) {
  const start = src.indexOf(`export const ${name}`);
  if (start === -1) throw new Error(`${name} is not exported from lib/drm/word-lists.ts`);
  // From the "=", not from the name: the type annotation `: WordList[]` carries a bracket
  // of its own, and starting at the name would open on that one and read nothing.
  const eq = src.indexOf('=', start);
  const open = src.indexOf('[', eq);
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === '[') depth++;
    else if (src[i] === ']') {
      depth--;
      if (depth === 0) return src.slice(open, i + 1);
    }
  }
  throw new Error(`${name} is not closed`);
}

/**
 * Evaluates one of those array literals.
 *
 * They are plain data — string and object literals, no imports, no calls — so this reads
 * them rather than adding a TypeScript loader for two constants. Anything that is not plain
 * data throws instead of silently producing something different from the original.
 */
function readArray(name) {
  const text = block(name);
  if (/[`$]|\bfunction\b|=>|\brequire\b|\bimport\b/.test(text)) {
    throw new Error(`${name} is no longer a plain data literal; this script must be updated.`);
  }
  return Function(`"use strict"; return (${text});`)();
}

const lists = readArray('WORD_LISTS');
const foils = readArray('UNRELATED_FOILS');

// Every check here is a transcription failure that would otherwise reach a class unnoticed.
if (lists.length === 0) throw new Error('WORD_LISTS is empty');
const sizes = new Set(lists.map(l => l.studyWords.length));
if (sizes.size !== 1) {
  throw new Error(`Lists are of different lengths (${[...sizes].join(', ')}); the recognition test assumes one length.`);
}
for (const list of lists) {
  if (!list.theme || !list.criticalLure) throw new Error(`List ${list.theme} is missing a theme or a lure`);
  if (list.studyWords.includes(list.criticalLure)) {
    throw new Error(`List ${list.theme} contains its own critical lure, which would destroy the effect.`);
  }
}
const everyStudied = new Set(lists.flatMap(l => l.studyWords));
const everyLure = new Set(lists.map(l => l.criticalLure));
for (const foil of foils) {
  if (everyStudied.has(foil) || everyLure.has(foil)) {
    throw new Error(`Foil "${foil}" is also a studied word or a lure, so it could not be a foil.`);
  }
}

const q = s => `'${String(s).replace(/'/g, "\\'")}'`;

const listLines = lists.map(list => {
  const words = list.studyWords
    .map((word, i) => `      { word: ${q(word)}, serialPosition: ${i + 1} },`)
    .join('\n');
  return `  {
    theme: ${q(list.theme)},
    lure: ${q(list.criticalLure)},
    words: [
${words}
    ],
  },`;
}).join('\n');

const foilLines = foils.map(word => `  { word: ${q(word)} },`).join('\n');

const out = `// DRM stimuli, extracted from lib/drm/word-lists.ts.
//
// GENERATED by scripts/build-drm-stimuli.mjs — do not edit by hand. A copy rather than an
// import, as with the other ported stimuli: that module pulls its types through the "@/"
// alias, which Node cannot resolve when the offline suites load these files directly.
//
// ${lists.length} themed lists of ${lists[0].studyWords.length} words, each with the critical lure that is never shown,
// plus ${foils.length} unrelated foils for the recognition test.

export interface DrmWord { word: string; serialPosition: number; }
export interface DrmList { theme: string; lure: string; words: DrmWord[] }

export const DRM_LISTS: DrmList[] = [
${listLines}
];

/** Never studied and unrelated to any theme: the baseline for a false alarm. */
export const DRM_FOILS: { word: string }[] = [
${foilLines}
];

export const DRM_WORDS_PER_LIST = ${lists[0].studyWords.length};
`;

writeFileSync(TARGET, out, 'utf8');
console.log(
  `Wrote ${TARGET}\n  ${lists.length} lists x ${lists[0].studyWords.length} words, ` +
  `${lists.length} lures, ${foils.length} foils`,
);
