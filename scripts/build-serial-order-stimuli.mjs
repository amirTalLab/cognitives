// Regenerates lib/experiment-runtime/stimuli/serial-order-lists.ts from the hand-built
// experiment.
//
//   node scripts/build-serial-order-stimuli.mjs
//
// The two study lists are Hebrew. A transposed letter would be invisible to anyone reading
// this file and would silently turn a studied word into one that can never be recalled, so
// they are read out of lib/serial-order/stimuli.ts rather than copied by hand.
//
// The arithmetic filler is different: the original GENERATES a fresh problem each time, and
// a definition needs a pool. This emits a bank of them using the original's own rules —
// same operators, same operand ranges — deterministically, so the file is stable between
// runs and a diff means something.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE = join(process.cwd(), 'lib', 'serial-order', 'stimuli.ts');
const TARGET = join(process.cwd(), 'lib', 'experiment-runtime', 'stimuli', 'serial-order-lists.ts');

if (!existsSync(SOURCE)) {
  console.error(`Cannot find ${SOURCE}. Run this from the repository root.`);
  process.exit(1);
}

const src = readFileSync(SOURCE, 'utf8');

/** Reads one `export const NAME ... = [ ... ];` array literal out of the source. */
function readArray(name) {
  const start = src.indexOf(`export const ${name}`);
  if (start === -1) throw new Error(`${name} is not exported from lib/serial-order/stimuli.ts`);
  // From the "=", since the type annotation `: StudyWord[]` carries a bracket of its own.
  const open = src.indexOf('[', src.indexOf('=', start));
  let depth = 0;
  let text = '';
  for (let i = open; i < src.length; i++) {
    if (src[i] === '[') depth++;
    else if (src[i] === ']') depth--;
    if (depth === 0) { text = src.slice(open, i + 1); break; }
  }
  if (!text) throw new Error(`${name} is not closed`);
  if (/[`$]|\bfunction\b|=>|\brequire\b|\bimport\b/.test(text)) {
    throw new Error(`${name} is no longer a plain data literal; this script must be updated.`);
  }
  return Function(`"use strict"; return (${text});`)();
}

const list1 = readArray('STUDY_LIST_1');
const list2 = readArray('STUDY_LIST_2');

// Every check here is a transcription failure that would otherwise reach a class unnoticed.
if (list1.length !== list2.length) {
  throw new Error(`The lists differ in length (${list1.length} vs ${list2.length}); the serial-position curve assumes one length.`);
}
for (const [name, list] of [['STUDY_LIST_1', list1], ['STUDY_LIST_2', list2]]) {
  list.forEach((w, i) => {
    if (!w.word || typeof w.word !== 'string') throw new Error(`${name} item ${i + 1} has no word`);
    if (w.serial_position !== i + 1) {
      throw new Error(`${name} item ${i + 1} claims serial position ${w.serial_position}`);
    }
  });
  if (new Set(list.map(w => w.word)).size !== list.length) {
    throw new Error(`${name} repeats a word, so a recall could not be attributed to one position.`);
  }
}
const shared = list1.map(w => w.word).filter(w => list2.some(x => x.word === w));
if (shared.length) {
  throw new Error(`Both lists contain ${shared.join(', ')}, so a recall could belong to either session.`);
}

/**
 * The regions the dashboard averages over: primacy 1-7, middle 8-13, recency 14-20.
 * Read off app/serialOrder/teacher/page.tsx rather than invented here.
 */
const PRIMACY_END = 7;
const MIDDLE_END = 13;
const regionOf = pos => (pos <= PRIMACY_END ? 'primacy' : pos <= MIDDLE_END ? 'middle' : 'recency');

if (list1.length !== 20) {
  throw new Error(`The regions 1-7 / 8-13 / 14-20 assume 20 words, but the lists hold ${list1.length}.`);
}

// ── The arithmetic bank ───────────────────────────────────────────────────────
// The original's rules, from generateArithmeticProblem: + is (10..89) + (5..44),
// - is (20..89) - (5..a-5), x is (2..10) x (2..10).

let seed = 987654321;
const rand = n => Math.floor((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648 * n);

const problems = [];
const seen = new Set();
while (problems.length < 240) {
  const op = ['+', '-', '×'][rand(3)];
  let a, b, answer;
  if (op === '+') { a = rand(80) + 10; b = rand(40) + 5; answer = a + b; }
  else if (op === '-') { a = rand(70) + 20; b = rand(a - 5) + 5; answer = a - b; }
  else { a = rand(9) + 2; b = rand(9) + 2; answer = a * b; }

  const problem = `${a} ${op} ${b}`;
  if (seen.has(problem)) continue;
  seen.add(problem);
  problems.push({ problem, answer });
}

const q = s => `'${String(s).replace(/'/g, "\\'")}'`;

const listLines = list => list
  .map(w => `  { word: ${q(w.word)}, serialPosition: ${w.serial_position}, region: ${q(regionOf(w.serial_position))} },`)
  .join('\n');

const out = `// Serial-order stimuli, extracted from lib/serial-order/stimuli.ts.
//
// GENERATED by scripts/build-serial-order-stimuli.mjs — do not edit by hand. The study
// words are Hebrew and were read out of the original rather than retyped: a transposed
// letter here would be invisible and would turn a studied word into one that can never be
// recalled.
//
// \`region\` is the third of the list each position falls in, as the teacher dashboard
// averages them: primacy 1-${PRIMACY_END}, middle ${PRIMACY_END + 1}-${MIDDLE_END}, recency ${MIDDLE_END + 1}-${list1.length}.
//
// The arithmetic is a BANK rather than a generator, since a definition draws from pools.
// Built with the original's own operand ranges, deterministically.

export interface SoWord { word: string; serialPosition: number; region: string }
export interface SoProblem { problem: string; answer: number }

export const SO_LIST_1: SoWord[] = [
${listLines(list1)}
];

export const SO_LIST_2: SoWord[] = [
${listLines(list2)}
];

export const SO_PROBLEMS: SoProblem[] = [
${problems.map(p => `  { problem: ${q(p.problem)}, answer: ${p.answer} },`).join('\n')}
];

export const SO_WORDS_PER_LIST = ${list1.length};
`;

writeFileSync(TARGET, out, 'utf8');
console.log(
  `Wrote ${TARGET}\n  2 lists x ${list1.length} words, ${problems.length} arithmetic problems`,
);
