// Builds the two-step task's trials from the hand-built original.
//
//   node scripts/build-two-step-stimuli.mjs
//
// Writes lib/experiment-runtime/stimuli/two-step-trials.ts.
//
// Every number here is ported from lib/two-step-task/stimuli.ts: the 70% common transition,
// the Gaussian drift of the reward probabilities and the 0.25-0.75 bounds they bounce off.
//
// WHAT THIS PRE-DRAWS, and why. A trial has two random events — which world the first choice
// leads to, and whether the second choice pays — and the schema has no arithmetic on purpose.
// So each trial carries the outcome of EVERY branch the participant could take, drawn here:
// where "left" would lead and where "right" would, and whether each of the four
// world-and-choice pairs pays. At run time the definition looks up the branch that happened.
//
// That is not a workaround. It means the whole trial is decided before it starts and is
// reconstructable from its stored row — you can see what would have happened had they chosen
// the other symbol, which is exactly the counterfactual a model-based analysis needs.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const COMMON_PROB = 0.7;
const DRIFT_SD = 0.025;
const PROB_MIN = 0.25;
const PROB_MAX = 0.75;
const MAIN_TRIALS = 100;
const PRACTICE_TRIALS = 10;
/** Independent walks, so two people never face the same run of luck. */
const WALKS = 12;

let seed = 20260924;
const rand = () => {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 4294967296;
};

/** Reflected at the bounds rather than clipped, so the walk keeps moving at the edges. */
const clamp = p => {
  if (p < PROB_MIN) return 2 * PROB_MIN - p;
  if (p > PROB_MAX) return 2 * PROB_MAX - p;
  return p;
};

const gaussian = () => {
  let u = 0;
  let v = 0;
  while (u === 0) u = rand();
  while (v === 0) v = rand();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
};

const round2 = n => Math.round(n * 100) / 100;

/**
 * One participant's run: a slow random walk over four reward probabilities.
 *
 * Slow is the point. If the best option changed abruptly nobody could track it, and if it
 * never changed there would be nothing to learn — the drift is what forces a participant to
 * keep updating, which is what the task measures.
 */
function walk(nTrials, label) {
  let probs = [0, 1, 2, 3].map(() => 0.25 + rand() * 0.5);
  const trials = [];

  for (let i = 0; i < nTrials; i++) {
    if (i > 0) probs = probs.map(p => clamp(p + gaussian() * DRIFT_SD));

    // Where each first choice would lead. Usually the common world, sometimes the rare one —
    // and the rare transitions are the whole experiment: a reward after a rare transition
    // teaches a model-based learner something different from a model-free one.
    const leftCommon = rand() < COMMON_PROB;
    const rightCommon = rand() < COMMON_PROB;

    // Whether each world-and-choice pair pays, drawn against this trial's probabilities.
    const paid = probs.map(p => rand() < p);

    trials.push({
      walk: label,
      index: i,
      stateIfLeft: leftCommon ? 'A' : 'B',
      stateIfRight: rightCommon ? 'B' : 'A',
      transitionIfLeft: leftCommon ? 'common' : 'rare',
      transitionIfRight: rightCommon ? 'common' : 'rare',
      // Keyed by world so an outcome can pick the pair, then the choice within it.
      rewardA: { left: paid[0], right: paid[1] },
      rewardB: { left: paid[2], right: paid[3] },
      probA1: round2(probs[0]),
      probA2: round2(probs[1]),
      probB1: round2(probs[2]),
      probB2: round2(probs[3]),
    });
  }
  return trials;
}

const main = Array.from({ length: WALKS }, (_, i) => walk(MAIN_TRIALS, `w${i + 1}`));
const practice = walk(PRACTICE_TRIALS, 'practice');

const literal = rows => rows.map(r => `  ${JSON.stringify(r)},`).join('\n');

const out = `// Two-step task trials.
//
// GENERATED by scripts/build-two-step-stimuli.mjs — do not edit by hand.
//
// Ported from lib/two-step-task/stimuli.ts. Each trial carries the outcome of every branch
// its participant could take: where each first choice would lead, and whether each of the
// four world-and-choice pairs pays. The definition looks up the branch that happened, so
// nothing is computed while someone is playing and the whole trial — including the road not
// taken — is readable from its stored row.
//
// ${WALKS} independent walks of ${MAIN_TRIALS} trials. A participant is assigned one, so no two
// people necessarily face the same run of luck, exactly as the original redraws its walk per
// session.

export interface TwoStepTrial {
  walk: string;
  index: number;
  stateIfLeft: string;
  stateIfRight: string;
  transitionIfLeft: string;
  transitionIfRight: string;
  rewardA: { left: boolean; right: boolean };
  rewardB: { left: boolean; right: boolean };
  probA1: number;
  probA2: number;
  probB1: number;
  probB2: number;
}

${main.map((rows, i) =>
  `export const TS_WALK_${i + 1}: TwoStepTrial[] = [\n${literal(rows)}\n];`,
).join('\n\n')}

export const TS_PRACTICE: TwoStepTrial[] = [
${literal(practice)}
];

export const TS_WALKS: TwoStepTrial[][] = [${main.map((_, i) => `TS_WALK_${i + 1}`).join(', ')}];
`;

writeFileSync(join(process.cwd(), 'lib', 'experiment-runtime', 'stimuli', 'two-step-trials.ts'), out);
console.log(`${WALKS} walks x ${MAIN_TRIALS} trials + ${PRACTICE_TRIALS} practice`);
